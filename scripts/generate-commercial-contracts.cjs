// Rebuild only the commercial wire contracts from the deployed Swagger snapshot.
const fs = require('node:fs');
const snapshot = JSON.parse(fs.readFileSync('docs/commercial-openapi.json', 'utf8'));
const schemas = snapshot.components.schemas;
const names = new Set();
function collect(name) {
  if (names.has(name)) return;
  if (!schemas[name]) throw new Error(`Missing commercial schema: ${name}`);
  names.add(name);
  for (const match of JSON.stringify(schemas[name]).matchAll(/#\/components\/schemas\/([^" ]+)/g))
    collect(match[1]);
}
for (const root of [
  'CommercialCatalogResponse',
  'SubscriptionDetails',
  'DoctorSubscriptionPagedResponse',
  'SubscriptionSelection',
  'SubscriptionMutationRequest',
  'LegacyTransitionEnrollmentBatch',
])
  collect(root);
function type(schema) {
  let result;
  if (schema.$ref) result = schema.$ref.split('/').at(-1);
  else if (schema.enum) result = schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  else if (schema.type === 'array') result = `readonly (${type(schema.items)})[]`;
  else if (schema.properties)
    result =
      '{ ' +
      Object.entries(schema.properties)
        .map(([key, value]) => `readonly ${key}: ${type(value)};`)
        .join(' ') +
      ' }';
  else if (['integer', 'number'].includes(schema.type)) result = 'number';
  else if (schema.type === 'string' || schema.type === 'boolean') result = schema.type;
  else result = 'unknown';
  return result + (schema.nullable ? ' | null' : '');
}
const contractSource =
  '// Generated by scripts/generate-commercial-contracts.cjs from the deployed commercial Swagger.\n' +
  [...names].map((name) => `export type ${name} = ${type(schemas[name])};`).join('\n') +
  '\n';
// Keep one feature-scoped source of wire truth, without unrelated API schemas.
snapshot.paths = Object.fromEntries(
  Object.entries(snapshot.paths)
    .filter(([route]) => /subscription|commercial/.test(route))
    .map(([route, operations]) => [
      route,
      Object.fromEntries(
        Object.entries(operations).map(([verb, operation]) => [
          verb,
          {
            description: operation.description,
            parameters: operation.parameters,
            requestBody: operation.requestBody,
            responses: Object.fromEntries(
              Object.entries(operation.responses ?? {}).filter(([status]) =>
                status.startsWith('2'),
              ),
            ),
          },
        ]),
      ),
    ]),
);
snapshot.components.schemas = Object.fromEntries([...names].map((name) => [name, schemas[name]]));
fs.writeFileSync('docs/commercial-openapi.json', JSON.stringify(snapshot, null, 2) + '\n');
require('prettier')
  .format(contractSource, { parser: 'typescript', singleQuote: true, printWidth: 100 })
  .then((formatted) => {
    fs.writeFileSync('src/app/domains/subscriptions/contracts.ts', formatted);
    console.log(`Generated ${names.size} commercial wire contracts.`);
  })
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
